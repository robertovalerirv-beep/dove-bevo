// Writes public/map/<theme>.<hash>.json (served with immutable cache, see public/_headers) and
// src/app/lib/map-styles.generated.ts with their URLs. The result is committed; rerun only to
// refresh from OpenFreeMap or after a token change (tests/unit/map-styles.test.ts fails if stale).
// Usage: node scripts/build-map-styles.mjs
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { deriveStyle } from "./map-styles.ts";

const tokens = JSON.parse(readFileSync("docs/brand/tokens.json", "utf8"));
const SOURCES = { light: "positron", dark: "dark" };
const NAMES = { light: "bancone", dark: "fuori-orario" };

mkdirSync("public/map", { recursive: true });
for (const f of readdirSync("public/map")) rmSync(`public/map/${f}`);
const urls = {};
for (const theme of ["light", "dark"]) {
  const base = await (
    await globalThis.fetch(`https://tiles.openfreemap.org/styles/${SOURCES[theme]}`)
  ).json();
  const json = JSON.stringify(deriveStyle(base, tokens, theme));
  const hash = createHash("sha256").update(json).digest("hex").slice(0, 8);
  const file = `${NAMES[theme]}.${hash}.json`;
  writeFileSync(`public/map/${file}`, json);
  urls[theme] = `/map/${file}`;
}
writeFileSync(
  "src/app/lib/map-styles.generated.ts",
  `// Generated by scripts/build-map-styles.mjs: do not edit.\nexport const MAP_STYLES = ${JSON.stringify(urls, null, 2)} as const;\n`,
);
console.log("map styles written", urls);
